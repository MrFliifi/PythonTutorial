# 0.0.4: None Value

# In Python gibt es einen speziellen Wert namens "None". Dieser Wert wird verwendet, 
# um das Fehlen eines Wertes zu kennzeichnen. None ist ein eigenständiger Datentyp 
# und wird oft als "Nullwert" oder "leerer Wert" bezeichnet. None hat nur einen Wert, 
# nämlich None selbst. Es ist wichtig zu verstehen, dass None nicht dasselbe ist wie 0, 
# False oder ein leerer String. None repräsentiert das Fehlen eines Wertes, während 
# 0, False und leere Strings gültige Werte sind.

