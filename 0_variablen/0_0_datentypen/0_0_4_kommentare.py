# Kommentare haben keinen Datentyp. Wir behandeln sie trotzdem hier.

# Kommentare werden durch ein # gekennzeichnet. Alles, was nach einem # steht,
# wird von Python ignoriert. Das gilt aber nur für die Zeile, in der das # steht. 

"Ich kann das # auch hinter einer Anweisung verwenden." # Alles was vor dem # steht, 
# wird von Python ausgeführt. Alles was nach dem # steht, wird ignoriert.

# Wenn ich also x = 1 + 1 eingebe und das script ausführe, passiert nichts.
x = 1 + 1 # Das wiederum würde Python ausführen.

