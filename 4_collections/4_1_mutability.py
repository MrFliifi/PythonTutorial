# 4.1: Mutability

# Mutability ist ein generelles Konzept in der Programmierung. Es befasst sich damit, ob 
# eine Variable veränderbar ist, oder nicht. Ist eine Variable veränderbar, ist sie mutable. 
# Ist sie unveränderbar, ist sie immutable. Bisher haben wir nur mit Variablen gearbeitet, 
# die mutable sind. In den folgenden Kapiteln werden wir uns aber mit Variablen auseinander
# -setzen, die immutable sind.