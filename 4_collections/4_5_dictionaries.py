# 4.5: Dictionaries

# dictionaries (dicts) sind ein container. dicts sind ordered und mutable, aber sie 
# erlauben keine duplikaten key values.
# dicts erkennt man am folgenden Syntax:

dict_name = {
  "brand": ["Ford", "Toyota"],
  "model": "Mustang",
  "year": 1964
}
print(dict_name)
print()

# Zuerst definiert man einen Namen. Darauf folgt der assignment operator =. Das dict wird
# dann mit { geöffnet. Man bilded beliebig viele key-value-pairs. Jedem key können beliebig
# viele Werte, von jedem beliebigen Datentyp, zugeordnet werden. Jeder key muss einzigartig
# sein. Abschließen tut man das dict mit }.

