# 2. Stein-Schere-Papier
# Schreibe ein Konsolen-Script, das:
# - Dem Nutzer erlaubt auszuwählen wie viele Runden er spielen möchte
# - Dem Nutzer erlaubt zwischen "Stein", "Schere", oder "Papier" zu wählen
# - Das zufällig zwischen "Stein", "Schere", oder "Papier" auswählt und die Auswahl in die Konsole ausgibt
# - Die Wahl des Nutzers und des Scripts vergleicht und den Sieger feststellt
# - Einen Score speichert und Anzeigt
# - Anhand vom Score den Sieger über alle Runden hinweg feststellt (Bei 5 Runden gewinnt der Erste bei 3 Punkten usw.)
