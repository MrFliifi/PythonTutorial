# 1.1: Assignment Operators

# Python bietet auch Operatoren, mit denen man das Ergebnis der Operation auch direkt
# in eine Variabel schreiben kann. Wir kennen bereits = . Python bietet aber noch mehr.
# Der Aufbau ist immer der gleiche. Man nimmt einen beliebigen anderen Operator uns stellt
# ein = hinten dran. Hier ein paar Beispiele:

x = 0    # assignment
x += 1   # addition mit assignment
x -= 1   # substraction mit assignment
x *= 2   # multiplication mit assignment
x /= 2   # divission mit assignment
x %= 2   # modulo mit assignment
x //= 3  # integer divission mit assignment